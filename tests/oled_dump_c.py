"""Generates firmware/main/cat_face.h from the poses in oled_animate.py.

Each unique pose is dumped as a 1024-byte uint8_t array in SSD1306
horizontal-page order — matches firmware/main/oled.c's framebuffer
exactly, so the firmware can `memcpy` into the face panel's fb and
flush. Per-state animation tables list the frames + per-frame duration
that the firmware's face task plays in a loop.

Run:
    .venv/Scripts/python.exe tests/oled_dump_c.py > firmware/main/cat_face.h
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from oled_animate import (  # noqa: E402
    ACTIVE_LAYOUT,
    Q_STAGE_FULL,
    make_idle_closed,
    make_idle_open,
    make_idle_squint,
    make_listening,
    make_listening_blink,
    make_speak_o,
    make_speak_omega,
    make_speak_quiet,
    make_thinking,
)

OLED_W = ACTIVE_LAYOUT.W
OLED_H = ACTIVE_LAYOUT.H


def to_c_bytes(img) -> list[int]:
    """Pack a 128×64 1-bit image into firmware-fb byte order (8 pages × 128
    bytes; bit 0 of each byte = top pixel of the page)."""
    px = img.load()
    out: list[int] = []
    for page in range(OLED_H // 8):
        for x in range(OLED_W):
            b = 0
            for bit in range(8):
                if px[x, page * 8 + bit]:
                    b |= 1 << bit
            out.append(b)
    return out


# Unique pose bitmaps used across the animations.
# `idle_open` doubles as listening's "stage 0" (no question mark drawn yet).
FRAMES: dict[str, callable] = {
    "idle_open":   make_idle_open,
    "idle_squint": make_idle_squint,
    "idle_closed": make_idle_closed,
    "listen_q1":   lambda: make_listening(stage=1),
    "listen_q2":   lambda: make_listening(stage=2),
    "listen_q3":   lambda: make_listening(stage=3),
    "listen_q4":   lambda: make_listening(stage=4),
    "listen_q5":   lambda: make_listening(stage=Q_STAGE_FULL),
    "listen_blink": lambda: make_listening_blink(stage=Q_STAGE_FULL),
    "think_0":     lambda: make_thinking(0),
    "think_1":     lambda: make_thinking(1),
    "think_2":     lambda: make_thinking(2),
    "think_3":     lambda: make_thinking(3),
    "speak_omega": make_speak_omega,
    "speak_o":     make_speak_o,
    "speak_quiet": make_speak_quiet,
}

# Per-state animation: list of (frame_name, duration_ms).
ANIMATIONS: dict[str, list[tuple[str, int]]] = {
    "idle": [
        ("idle_open",   4000),
        ("idle_squint",   50),
        ("idle_closed",  100),
        ("idle_squint",   50),
    ],
    "listening": [
        ("idle_open",    250),  # blank — about to start drawing
        ("listen_q1",    130),
        ("listen_q2",    130),
        ("listen_q3",    130),
        ("listen_q4",    130),
        ("listen_q5",   1500),
        ("listen_blink",  80),
        ("listen_q5",    600),
        ("listen_q4",     80),
        ("listen_q3",     80),
        ("listen_q2",     80),
        ("listen_q1",     80),
        ("idle_open",    250),
    ],
    "thinking": [
        ("think_0", 250),
        ("think_1", 320),
        ("think_2", 320),
        ("think_3", 600),
    ],
    "speaking": [
        ("speak_omega", 240),
        ("speak_o",     240),
        ("speak_omega", 240),
        ("speak_quiet", 180),
    ],
}


def main() -> None:
    print("// AUTO-GENERATED by tests/oled_dump_c.py — do not edit by hand.")
    print("// Source poses live in tests/oled_animate.py; rerun the dump script")
    print("// after editing them to regenerate this file.")
    print()
    print("#pragma once")
    print()
    print("#include <stddef.h>")
    print("#include <stdint.h>")
    print()
    print("#include \"oled.h\"  // for OLED_FB_BYTES")
    print()

    # Bitmap arrays.
    for name, fn in FRAMES.items():
        img = fn()
        if img.size != (OLED_W, OLED_H) or img.mode != "1":
            sys.exit(f"frame {name}: expected 128×64 1-bit, got {img.size} {img.mode}")
        out = to_c_bytes(img)
        if len(out) != 1024:
            sys.exit(f"frame {name}: expected 1024 bytes, got {len(out)}")
        print(f"static const uint8_t cat_{name}[OLED_FB_BYTES] = {{")
        for i in range(0, len(out), 16):
            chunk = out[i:i + 16]
            print("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
        print("};")
        print()

    # Frame struct.
    print("typedef struct {")
    print("    const uint8_t *bitmap;")
    print("    uint16_t       duration_ms;")
    print("} face_frame_t;")
    print()

    # Per-state animation arrays.
    for state, frames in ANIMATIONS.items():
        n = len(frames)
        print(f"static const face_frame_t cat_anim_{state}[{n}] = {{")
        for fname, dur in frames:
            print(f"    {{ cat_{fname}, {dur} }},")
        print("};")
        print()

    # Lookup tables indexed by app_state_t (see app_state.h):
    #   0 = BOOT, 1 = IDLE, 2 = LISTENING, 3 = THINKING, 4 = SPEAKING
    print("// Lookup tables indexed by app_state_t (app_state.h):")
    print("//   0 BOOT  1 IDLE  2 LISTENING  3 THINKING  4 SPEAKING")
    print("static const face_frame_t * const cat_anim_by_state[] = {")
    print("    cat_anim_idle,       // BOOT       — show idle face while booting")
    print("    cat_anim_idle,       // IDLE")
    print("    cat_anim_listening,  // LISTENING")
    print("    cat_anim_thinking,   // THINKING")
    print("    cat_anim_speaking,   // SPEAKING")
    print("};")
    print()
    print("static const size_t cat_anim_len_by_state[] = {")
    for state in ("idle", "idle", "listening", "thinking", "speaking"):
        n = len(ANIMATIONS[state])
        print(f"    {n},")
    print("};")


if __name__ == "__main__":
    main()
